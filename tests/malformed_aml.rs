use acpi::aml::{AmlError, Interpreter};
use aml_test_tools::handlers::null_handler::NullHandler;

#[test]
fn malformed_if_else_length_returns_error_without_underflow() {
    let interpreter = Interpreter::new(NullHandler, 2);
    let aml = [
        // Name (TST0, One), followed by the minimized malformed If/Else AML input.
        0x08, b'T', b'S', b'T', b'0', 0x01, 0xa0, 0x74, 0x00, 0x00, 0x04, 0xa0, 0x74, 0x00, 0xff, 0xff, 0xa1, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xff, 0xa0,
        0x74, 0x0a,
    ];

    assert!(matches!(
        interpreter.load_table(&aml),
        Err(AmlError::InvalidPackageLength | AmlError::RunOutOfStream)
    ));
}
